-- escuela: lectura pública, escritura solo usuarios activos
CREATE POLICY "Lectura pública de escuelas"
  ON public.escuela FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE POLICY "Gestión de escuelas para usuarios activos"
  ON public.escuela FOR ALL
  TO authenticated
  USING (public.es_usuario_activo())
  WITH CHECK (public.es_usuario_activo());

-- usuario: solo usuarios autenticados ven perfiles; cada usuario edita su propio registro
CREATE POLICY "Usuarios autenticados leen perfiles"
  ON public.usuario FOR SELECT
  TO authenticated
  USING (true);

CREATE POLICY "Usuario actualiza su propio perfil"
  ON public.usuario FOR UPDATE
  TO authenticated
  USING (id_auth = auth.uid())
  WITH CHECK (id_auth = auth.uid());

-- publicacion: público solo ve estado = 'publicado'; usuarios activos gestionan
CREATE POLICY "Lectura pública de publicaciones publicadas"
  ON public.publicacion FOR SELECT
  TO anon, authenticated
