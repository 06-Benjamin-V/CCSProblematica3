-- =====================================================
-- Funciones auxiliares para políticas RLS
-- =====================================================
CREATE OR REPLACE FUNCTION public.es_usuario_activo()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.usuario u
    WHERE u.id_auth = auth.uid()
      AND u.activo = true
  );
$$;

CREATE OR REPLACE FUNCTION public.mi_id_usuario()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT u.id_usuario
  FROM public.usuario u
  WHERE u.id_auth = auth.uid()
    AND u.activo = true
  LIMIT 1;
$$;

