-- archivo: lectura pública si pertenece a publicación publicada
CREATE POLICY "Lectura pública de archivos de publicaciones publicadas"
  ON public.archivo FOR SELECT
  TO anon, authenticated
  USING (
    public.es_usuario_activo()
    OR EXISTS (
      SELECT 1 FROM public.publicacion p
      WHERE p.id_publicacion = archivo.publicacion_id_publicacion
        AND p.estado = 'publicado'
    )
  );

